const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  bg,
  de,
  en,
};

type TranslationValues = Record<string, string | number>;

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: TranslationValues) => string;
  option: (value: string | number) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

const LANGUAGE_STORAGE_KEY = "monsters-language";
const LANGUAGE_EVENT = "monsters-language-change";

function getBrowserLocale(): Locale {
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return saved && LOCALES.includes(saved as Locale) ? (saved as Locale) : "en";
}

function subscribeToLanguage(onChange: () => void) {
  window.addEventListener("storage", onChange);
  window.addEventListener(LANGUAGE_EVENT, onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener(LANGUAGE_EVENT, onChange);
  };
}

function getServerLocale(): Locale {
  return "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const locale = useSyncExternalStore(
    subscribeToLanguage,
    getBrowserLocale,
    getServerLocale,
  );

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((nextLocale: Locale) => {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLocale);
    window.dispatchEvent(new Event(LANGUAGE_EVENT));
  }, []);

  const t = useCallback(
    (key: TranslationKey, values?: TranslationValues) => {
      let result = dictionaries[locale][key];
      if (values) {
        Object.entries(values).forEach(([name, value]) => {
          result = result.replaceAll(`{{${name}}}`, String(value));
        });
      }
      return result;
    },
    [locale],
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t,
      option: (optionValue) =>
        t(`option.${String(optionValue)}` as TranslationKey),
    }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside LanguageProvider");
  return context;
}

export function useLocalizedTitle(key: TranslationKey) {
  const { t } = useI18n();
  useEffect(() => {
    document.title = t(key);
  }, [key, t]);
}

export function LanguageSwitcher({ className = "" }: { className?: string }) {
  const { locale, setLocale, t } = useI18n();
  return (
    <div
      className={`language-switcher ${className}`.trim()}
      role="group"
      aria-label={t("language.label")}
    >
      {LOCALES.map((candidate) => (
        <button
          key={candidate}
          type="button"
          className={locale === candidate ? "selected" : ""}
          aria-pressed={locale === candidate}
          aria-label={t(`language.${candidate}` as TranslationKey)}
          title={t(`language.${candidate}` as TranslationKey)}
          onClick={() => setLocale(candidate)}
        >
          {candidate === "bg" ? "БГ" : candidate.toUpperCase()}
        </button>
      ))}
    </div>
  );
}

export function LanguageSelect({ className = "" }: { className?: string }) {
  const { locale, setLocale, t } = useI18n();
  const choices: Locale[] = ["en", "de", "bg"];
  return (
    <label className={`language-select ${className}`.trim()}>
      <span>{t("language.label")}</span>
      <select
        value={locale}
        aria-label={t("language.label")}
        onChange={(event) => setLocale(event.target.value as Locale)}
      >
        {choices.map((candidate) => (
          <option key={candidate} value={candidate}>
            {t(`language.${candidate}` as TranslationKey)}
          </option>
        ))}
      </select>
    </label>
  );
}
